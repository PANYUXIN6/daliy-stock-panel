// @vitest-environment jsdom
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { accountStorage, activateSession, sessionFetch, lockSession, migrateInitialAdminStorage, sessionEventSource } from './sessionRuntime'

describe('account session boundary', () => {
  beforeEach(() => { localStorage.clear(); vi.restoreAllMocks(); vi.unstubAllGlobals() })
  it('never restores another account or legacy unowned data', () => {
    localStorage.setItem('draft', 'legacy')
    activateSession('a')
    expect(accountStorage.getItem('draft')).toBeNull()
    accountStorage.setItem('draft', 'private-a')
    activateSession('b')
    expect(accountStorage.getItem('draft')).toBeNull()
    accountStorage.setItem('draft', 'private-b')
    activateSession('a')
    expect(accountStorage.getItem('draft')).toBe('private-a')
  })
  it('locks on HTTP 401 without interpreting error text', async () => {
    activateSession('a')
    const locked = vi.fn()
    window.addEventListener('session-locked', locked, { once: true })
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response('{}', { status: 401 })))
    await sessionFetch('/api/watchlist')
    expect(locked).toHaveBeenCalledOnce()
    await expect(sessionFetch('/api/watchlist')).rejects.toThrow()
  })
  it('does not treat forbidden responses as logout', async () => {
    activateSession('a')
    vi.stubGlobal('fetch', vi.fn().mockImplementation(async () => new Response('{}', { status: 403 })))
    await sessionFetch('/api/settings')
    await sessionFetch('/api/watchlist')
    expect(fetch).toHaveBeenCalledTimes(2)
    lockSession()
  })
})

it('migrates old personal drafts to the initial admin without overwriting existing account data', () => {
  localStorage.setItem('strategy-draft', 'old-python-draft')
  localStorage.setItem('tf-query-cache', 'unowned-query-cache')
  activateSession('guest')
  expect(accountStorage.getItem('strategy-draft')).toBeNull()
  activateSession('initial-admin')
  migrateInitialAdminStorage('initial-admin')
  expect(accountStorage.getItem('strategy-draft')).toBe('old-python-draft')
  expect(accountStorage.getItem('tf-query-cache')).toBeNull()
  accountStorage.setItem('strategy-draft', 'new-personal-draft')
  migrateInitialAdminStorage('initial-admin')
  expect(accountStorage.getItem('strategy-draft')).toBe('new-personal-draft')
  activateSession('guest')
  expect(accountStorage.getItem('strategy-draft')).toBeNull()
})
it('releases a consumed response but still aborts a pending stream on lock', async () => {
  activateSession('a')
  const signals: AbortSignal[] = []
  vi.stubGlobal('fetch', vi.fn((_url, init) => {
    signals.push(init.signal)
    return Promise.resolve(new Response(signals.length === 1 ? 'complete' : new ReadableStream({ start() {} })))
  }))
  const complete = await sessionFetch('/api/watchlist')
  expect(await complete.text()).toBe('complete')
  await sessionFetch('/api/stream')
  lockSession()
  expect(signals[0].aborted).toBe(false)
  expect(signals[1].aborted).toBe(true)
  expect(accountStorage.getItem('draft')).toBeNull()
})

it('pins every business request to the current account and cannot be overridden by callers', async () => {
  activateSession('a')
  const fetchMock = vi.fn(async (_input: RequestInfo | URL, _init?: RequestInit) => new Response('{}'))
  vi.stubGlobal('fetch', fetchMock)
  const response = await sessionFetch('/api/watchlist', { headers: { 'X-Expected-User': 'b', Accept: 'application/json' } })
  await response.text()
  const headers = new Headers(fetchMock.mock.calls[0][1]?.headers)
  expect(headers.get('X-Expected-User')).toBe('a')
  expect(headers.get('Accept')).toBe('application/json')
  await sessionFetch('/api/auth/status', { headers: { 'X-Expected-User': 'b' } })
  expect(new Headers(fetchMock.mock.calls[1][1]?.headers).has('X-Expected-User')).toBe(false)
})
it('pins SSE reconnect URLs to the active account while preserving existing parameters', () => {
  activateSession('owner-a')
  const urls: string[] = []
  class Stream extends EventTarget { constructor(url: string) { super(); urls.push(url) }; close() {} }
  vi.stubGlobal('EventSource', Stream)
  const stream = sessionEventSource('/api/backtest/stream?key=run&expected_user_id=other')
  const url = new URL(urls[0])
  expect(url.searchParams.get('expected_user_id')).toBe('owner-a')
  expect(url.searchParams.get('key')).toBe('run')
  stream.close()
})
it('does not send business requests or SSE before the identity has been confirmed', async () => {
  vi.resetModules()
  const fresh = await import('./sessionRuntime')
  const fetchMock = vi.fn(async (_input: RequestInfo | URL, _init?: RequestInit) => new Response('{}'))
  vi.stubGlobal('fetch', fetchMock)
  await expect(fresh.sessionFetch('/api/watchlist')).rejects.toThrow('身份未确认')
  expect(() => fresh.sessionEventSource('/api/intraday/stream')).toThrow('身份未确认')
  expect(fetchMock).not.toHaveBeenCalled()
  await fresh.sessionFetch('/api/auth/status')
  expect(fetchMock).toHaveBeenCalledOnce()
})

it.each(['/api/auth/logout', '/api/auth/change-password'])('pins %s to the confirmed account and locks on a changed cookie', async (path) => {
  activateSession('a')
  const fetchMock = vi.fn(async (_input: RequestInfo | URL, _init?: RequestInit) => new Response('{"code":"SESSION_OWNER_CHANGED"}', { status: 401 }))
  vi.stubGlobal('fetch', fetchMock)
  const response = await sessionFetch(path, { method: 'POST', headers: { 'X-Expected-User': 'b' } })
  expect(new Headers(fetchMock.mock.calls[0][1]?.headers).get('X-Expected-User')).toBe('a')
  expect(await response.json()).toEqual({ code: 'SESSION_OWNER_CHANGED' })
  await expect(sessionFetch(path, { method: 'POST' })).rejects.toThrow('会话已锁定')
  expect(fetchMock).toHaveBeenCalledOnce()
})

it('requires an identity for auth mutations while login and status remain usable', async () => {
  vi.resetModules()
  const fresh = await import('./sessionRuntime')
  const fetchMock = vi.fn(async (_input: RequestInfo | URL, _init?: RequestInit) => new Response('{}'))
  vi.stubGlobal('fetch', fetchMock)
  await expect(fresh.sessionFetch('/api/auth/logout', { method: 'POST' })).rejects.toThrow('身份未确认')
  await expect(fresh.sessionFetch('/api/auth/change-password', { method: 'POST' })).rejects.toThrow('身份未确认')
  await fresh.sessionFetch('/api/auth/login', { method: 'POST' })
  expect(fetchMock).toHaveBeenCalledOnce()
  expect(new Headers(fetchMock.mock.calls[0][1]?.headers).has('X-Expected-User')).toBe(false)
})
